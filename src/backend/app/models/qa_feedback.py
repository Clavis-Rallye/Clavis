"""
QA feedback models: the notes a tester leaves through the feedback bar in a test session,
and the one-row step state that the session kit sets.

Not ``app.models.feedback``, the participants' rating of a run. This is a test tool, off by
default (``QA_FEEDBACK_ENABLED``).

Neither table has a foreign key. A tester crosses organizations, the operator console and
logged-out pages in one session, and a test scenario deletes an organization on purpose.
The organization slug and the role a page showed are free text in ``context``, which also
keeps ``qa_notes`` out of the cascade that ``app.services.org_deletion`` walks. Notes hold
no account identity and no address. The retention sweep removes them after
``QA_FEEDBACK_RETENTION_DAYS``.
"""

from datetime import datetime
from typing import Any

from sqlalchemy import BigInteger, Boolean, CheckConstraint, DateTime, Identity, SmallInteger, String, Text, func
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column

from app.database import Base
from app.models.base import UUIDMixin

QA_NOTE_KINDS = ("ok", "skip", "note", "back", "goto")
# The kinds that move the current step.
QA_MOVE_KINDS = ("ok", "skip", "back", "goto")


class QaNote(UUIDMixin, Base):
    """One event from the feedback bar: ok, skip, back and goto move the step, note is feedback.

    The columns carry their own comments. What they do not say:

    - ``seq`` is the cursor of ``GET /api/qa/notes?after=<seq>``.
    - ``step`` looks like ``A-04``.
    - ``text`` is required for ``note``, and for ``skip`` it is the reason.
    - ``trail`` holds at most 30 entries.
    """

    __tablename__ = "qa_notes"
    __table_args__ = (CheckConstraint("kind IN ('ok', 'skip', 'note', 'back', 'goto')", name="kind"),)

    seq: Mapped[int] = mapped_column(
        BigInteger,
        Identity(),
        nullable=False,
        unique=True,
        comment="Monotonic cursor for the session kit",
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        index=True,
        comment="Server time of the insert, drives retention",
    )
    client_id: Mapped[str] = mapped_column(
        String(64),
        nullable=False,
        unique=True,
        comment="Idempotency key generated by the bar",
    )
    kind: Mapped[str] = mapped_column(String(8), nullable=False, comment="ok, skip, back, goto or note")
    step: Mapped[str | None] = mapped_column(String(32), nullable=True, comment="Scenario step shown by the bar")
    text: Mapped[str | None] = mapped_column(Text, nullable=True, comment="The tester's words")
    route: Mapped[str | None] = mapped_column(String(500), nullable=True, comment="pathname plus search")
    selector: Mapped[str | None] = mapped_column(String(500), nullable=True, comment="Pointed element, CSS path")
    element_text: Mapped[str | None] = mapped_column(String(300), nullable=True, comment="Pointed element, text")
    context: Mapped[dict[str, Any]] = mapped_column(
        JSONB,
        nullable=False,
        server_default="{}",
        comment="role, org, lang, viewport, user_agent as the page saw them",
    )
    session_id: Mapped[str | None] = mapped_column(
        String(36), nullable=True, index=True, comment="The session the event belongs to"
    )
    step_title: Mapped[str | None] = mapped_column(
        String(300), nullable=True, comment="The card title of the step, kept when the plan goes"
    )
    target: Mapped[str | None] = mapped_column(String(32), nullable=True, comment="The step a goto asked for")
    moved: Mapped[bool] = mapped_column(
        Boolean, nullable=False, server_default="false", comment="Whether this event moved the step"
    )
    to_step: Mapped[str | None] = mapped_column(String(32), nullable=True, comment="The step that became current")
    answers_message: Mapped[str | None] = mapped_column(
        String(2000), nullable=True, comment="The assistant's message this note answered"
    )
    trail: Mapped[list[dict[str, Any]]] = mapped_column(
        JSONB, nullable=False, server_default="[]", comment="The bar's action trail since the step began"
    )

    def __repr__(self) -> str:
        return f"<QaNote(seq={self.seq}, kind={self.kind}, step={self.step})>"


class QaState(Base):
    """The session: its plan, the current step, the join key. Exactly one row, pinned to id=1.

    The plan may hold the logins of the stand. Only a joined browser (the key, whose
    SHA-256 hash is ``key_hash``) or the kit reads it. Retention clears an old plan.
    """

    __tablename__ = "qa_state"
    __table_args__ = (CheckConstraint("id = 1", name="singleton"),)

    id: Mapped[int] = mapped_column(SmallInteger, primary_key=True, server_default="1", comment="Always 1")
    step: Mapped[str | None] = mapped_column(String(32), nullable=True, comment="The current step id")
    plan: Mapped[list[dict[str, Any]]] = mapped_column(
        JSONB, nullable=False, server_default="[]", comment="Ordered steps with their cards"
    )
    key_hash: Mapped[str | None] = mapped_column(String(64), nullable=True, comment="SHA-256 hex of the join key")
    session_id: Mapped[str | None] = mapped_column(String(36), nullable=True, comment="The current session's id")
    message: Mapped[str | None] = mapped_column(Text, nullable=True, comment="The assistant's message for the tester")
    message_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    hidden: Mapped[bool] = mapped_column(
        Boolean,
        nullable=False,
        server_default="false",
        comment="Kit switch: every bar renders nothing",
    )
    session: Mapped[str | None] = mapped_column(String(100), nullable=True, comment="Session label")
    updated_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
